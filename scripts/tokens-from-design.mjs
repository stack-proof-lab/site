// Generates src/styles/tokens.css from the `colors:` block of DESIGN.md's YAML frontmatter.
// Custom properties only; no rules. Usage: node scripts/tokens-from-design.mjs [path/to/DESIGN.md]
import { readFileSync, writeFileSync } from 'node:fs';

const src = process.argv[2] ?? process.env.DESIGN_MD;
if (!src) throw new Error('Pass the path to DESIGN.md as the first argument or set DESIGN_MD.');
const text = readFileSync(src, 'utf8');
const fm = text.match(/^---\r?\n([\s\S]*?)\r?\n---/m);
if (!fm) throw new Error('No YAML frontmatter found in ' + src);

const lines = fm[1].split(/\r?\n/);
const start = lines.findIndex((l) => /^colors:\s*$/.test(l));
if (start < 0) throw new Error('No colors: block in frontmatter');

const out = [];
for (const line of lines.slice(start + 1)) {
  if (/^\S/.test(line)) break; // next top-level key ends the block
  const m = line.match(/^\s+([a-z0-9-]+):\s*"([^"]+)"\s*(?:#\s*(.*))?$/i);
  if (!m) continue;
  const [, name, value, note] = m;
  out.push(`  --color-${name}: ${value};${note ? ` /* ${note.replace(/\*\//g, '')} */` : ''}`);
}
if (out.length === 0) throw new Error('colors: block parsed to zero tokens');

const css = `/* Generated by scripts/tokens-from-design.mjs from DESIGN.md frontmatter (colors). Do not edit by hand. */\n:root {\n${out.join('\n')}\n}\n`;
writeFileSync('src/styles/tokens.css', css);
console.log(`tokens.css: ${out.length} colour tokens from ${src}`);
